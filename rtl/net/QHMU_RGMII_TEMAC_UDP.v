`ifndef QHMU_RGMII_TEMAC_UDP_V
`define QHMU_RGMII_TEMAC_UDP_V

// ============================================================================
// QHMU_RGMII_TEMAC_UDP
//
// Ethernet hardware path follows the Anlogic HX4S20_Ethernet_test reference:
//   50-MHz oscillator -> pll_gen -> 125-MHz MAC TX clock / 90-degree TXC
//   PHY RXC -> rx_pll -> TEMAC RGMII receive clock
//   TEMAC + client FIFOs -> official UDP/IP/ARP protocol stack
//   QHMU_NET_APP -> 8-byte QHMU status response / command adapter
//
// V5 changes:
//   * Preserve the exact RX valid polarity conversion used by the official demo.
//   * Add PLL-lock-qualified reset sequencing for TEMAC, both client FIFOs,
//     UDP/IP stack and application logic.
//   * Use asynchronous assertion and per-clock synchronous reset release.
//   * Expose RX PLL lock from the generated RX PLL wrapper.
// The old hand-written raw RGMII/ARP/UDP byte parser is deliberately not used.
// ============================================================================
module QHMU_RGMII_TEMAC_UDP (
    input  wire        i_clk_50m,
    input  wire        i_reset,

    input  wire        i_rgmii_rx_clk,
    input  wire        i_rgmii_rx_ctl,
    input  wire [3:0]  i_rgmii_rxd,
    output wire        o_rgmii_tx_clk,
    output wire        o_rgmii_tx_ctl,
    output wire [3:0]  o_rgmii_txd,

    input  wire [6:0]  i_status_brightness,
    input  wire [6:0]  i_status_contrast,
    input  wire [3:0]  i_status_transition,
    input  wire [5:0]  i_status_image_index,
    input  wire [5:0]  i_status_file_count,
    input  wire        i_status_auto,
    input  wire        i_status_audio_wait,

    output wire        o_cmd_toggle,
    output wire [3:0]  o_cmd_code,
    output wire [7:0]  o_cmd_value,

    output wire        o_dbg_rx_clk_heartbeat,
    output wire        o_dbg_rx_activity,
    output wire        o_dbg_phy_link,
    output wire        o_dbg_udp_seen,
    output reg         o_dbg_arp_error,
    output reg         o_dbg_ip_error,
    output reg  [7:0]  o_dbg_rx_good_count,
    output reg  [7:0]  o_dbg_rx_bad_count,
    output reg  [7:0]  o_dbg_rx_valid_byte_count,
    output reg  [7:0]  o_dbg_rx_nonzero_byte_count,
    output wire [7:0]  o_dbg_udp_packet_count,
    output reg         o_dbg_rx_fifo_overflow_seen,
    output reg         o_dbg_tx_fifo_overflow_seen,

    // Additional stage-by-stage diagnostics (all 8-bit saturating counters).
    output reg  [7:0]  o_dbg_fifo_rx_byte_count,
    output reg  [7:0]  o_dbg_fifo_rx_nonzero_count,
    output reg  [7:0]  o_dbg_fifo_rx_sof_count,
    output reg  [7:0]  o_dbg_fifo_rx_eof_count,
    output reg  [7:0]  o_dbg_app_rx_byte_count,
    output reg  [7:0]  o_dbg_stack_tx_byte_count,
    output reg  [7:0]  o_dbg_stack_tx_nonzero_count,
    output reg  [7:0]  o_dbg_mac_tx_byte_count,
    output reg  [7:0]  o_dbg_mac_tx_nonzero_count
);

    localparam [47:0] LOCAL_MAC = 48'h48D159E26A03;
    localparam [31:0] LOCAL_IP  = 32'hC0A8F002; // 192.168.240.2
    localparam [15:0] LOCAL_PORT = 16'd5001;
    localparam [31:0] PC_IP      = 32'hC0A8F064; // 192.168.240.100
    localparam [15:0] PC_PORT    = 16'd5002;
    localparam [1:0]  TRI_SPEED  = 2'b10;       // UDP client clock: 125 MHz

    // ------------------------------------------------------------------------
    // Official Anlogic clock structure.
    // pll_gen C1 = 125 MHz MAC TX clock; C4 = 125 MHz / 90-degree TX clock.
    // C2/C3/C4 are generated by the official PLL IP wrapper.
    // ------------------------------------------------------------------------
    wire net_pll_lock;
    wire net_clk125_feedback;
    wire net_clk125;
    wire net_clk12p5;
    wire net_clk25;
    wire net_clk125_90;

    pll_gen u_net_pll (
        .refclk    (i_clk_50m),
        .reset     (i_reset),
        .extlock   (net_pll_lock),
        .clk0_out  (net_clk125_feedback),
        .clk1_out  (net_clk125),
        .clk2_out  (net_clk12p5),
        .clk3_out  (net_clk25),
        .clk4_out  (net_clk125_90)
    );

    // Official RX PLL wrapper.  In the vendor reference the signal named
    // rx_clk_90 is generated by C1; its generated IP file specifies 0-degree
    // phase.  It is retained here to preserve the official clock-routing path.
    wire rx_clk_pll_0;
    wire rx_clk_pll_90_name;
    wire rx_clk_pll_250_unused;
    wire rx_pll_locked;

    // Start the RX PLL only after the 50-MHz reference PLL has locked.
    // The RX PLL lock output is then used to release the MAC/FIFO/protocol
    // reset tree. This avoids using an unqualified RX clock during startup.
    wire rx_pll_reset = i_reset | !net_pll_lock;

    rx_pll u_rx_pll (
        .refclk   (i_rgmii_rx_clk),
        .reset    (rx_pll_reset),
        .locked   (rx_pll_locked),
        .clk0_out (rx_clk_pll_0),
        .clk1_out (rx_clk_pll_90_name),
        .clk2_out (rx_clk_pll_250_unused)
    );

    // Global network reset is asserted whenever either clock PLL is not
    // locked. It is asynchronously asserted and synchronously released in
    // each clock domain below.
    wire net_reset_async = i_reset | !net_pll_lock | !rx_pll_locked;

    wire net_clk1p25;
    div_clk_gen u_net_clk_1p25 (
        .reset  (i_reset | !net_pll_lock),
        .clk_en (1'b1),
        .clk_in (net_clk12p5),
        .clk_out(net_clk1p25)
    );

    wire udp_clk;
    udp_clk_gen #(.DEVICE("EG4")) u_udp_clk_gen (
        .reset       (net_reset_async),
        .tri_speed   (TRI_SPEED),
        .clk_125_in  (net_clk125),
        .clk_12_5_in (net_clk12p5),
        .clk_1_25_in (net_clk1p25),
        .udp_clk_out (udp_clk)
    );

    // ------------------------------------------------------------------------
    // TEMAC client-side signals and configuration (same as official demo).
    // ------------------------------------------------------------------------
    wire        rx_clk_int;
    wire        rx_clk_en_int;
    wire [7:0]  rx_data;
    wire        rx_valid;
    wire        rx_correct_frame;
    wire        rx_error_frame;

    wire        tx_clk_int;
    wire        tx_clk_en_int;
    wire [7:0]  tx_data;
    wire        tx_valid;
    wire        tx_rdy;
    wire        tx_collision;
    wire        tx_retransmit;

    // ------------------------------------------------------------------------
    // Clock-domain reset tree.
    //
    // The official example ties several reset inputs low. For this integrated
    // HDMI design we use explicit reset sequencing instead. All resets are
    // active-high. Assertion is asynchronous; release is synchronized to the
    // destination clock. Separate synchronizers are required for each FIFO
    // clock port because the client FIFOs are dual-clock blocks.
    // ------------------------------------------------------------------------
    reg [2:0] udp_reset_pipe;
    reg [2:0] rx_reset_pipe;
    reg [2:0] tx_reset_pipe;

    always @(posedge udp_clk or posedge net_reset_async) begin
        if (net_reset_async)
            udp_reset_pipe <= 3'b111;
        else
            udp_reset_pipe <= {udp_reset_pipe[1:0], 1'b0};
    end

    always @(posedge rx_clk_int or posedge net_reset_async) begin
        if (net_reset_async)
            rx_reset_pipe <= 3'b111;
        else
            rx_reset_pipe <= {rx_reset_pipe[1:0], 1'b0};
    end

    always @(posedge tx_clk_int or posedge net_reset_async) begin
        if (net_reset_async)
            tx_reset_pipe <= 3'b111;
        else
            tx_reset_pipe <= {tx_reset_pipe[1:0], 1'b0};
    end

    wire udp_domain_reset = udp_reset_pipe[2];
    wire rx_domain_reset  = rx_reset_pipe[2];
    wire tx_domain_reset  = tx_reset_pipe[2];

    wire        tx_stop = 1'b0;
    wire [7:0]  tx_ifg_val = 8'h00;
    wire        pause_req = 1'b0;
    wire [15:0] pause_val = 16'h0000;
    wire [47:0] pause_source_addr = 48'h5AF1F2F3F4F5;

    // TEMAC's unicast address input is byte-reversed in the official demo.
    wire [47:0] unicast_address = {
        LOCAL_MAC[7:0], LOCAL_MAC[15:8], LOCAL_MAC[23:16],
        LOCAL_MAC[31:24], LOCAL_MAC[39:32], LOCAL_MAC[47:40]
    };
    wire [19:0] mac_cfg_vector = {
        1'b0, 2'b00, TRI_SPEED, 8'b00000010, 7'b0000010
    };

    wire        inband_link_status;
    wire [1:0]  inband_clock_speed;
    wire        inband_duplex_status;

    temac_block #(.DEVICE("EG4")) u_temac_block (
        .reset                (net_reset_async),
        .gtx_clk              (net_clk125),
        .gtx_clk_90           (net_clk125_90),
        .rx_clk               (rx_clk_int),
        .rx_clk_en            (rx_clk_en_int),
        .rx_data              (rx_data),
        .rx_data_valid        (rx_valid),
        .rx_correct_frame     (rx_correct_frame),
        .rx_error_frame       (rx_error_frame),
        .rx_status_vector     (),
        .rx_status_vld        (),
        .tx_clk               (tx_clk_int),
        .tx_clk_en            (tx_clk_en_int),
        .tx_data              (tx_data),
        .tx_data_en           (tx_valid),
        .tx_rdy               (tx_rdy),
        .tx_stop              (tx_stop),
        .tx_collision         (tx_collision),
        .tx_retransmit        (tx_retransmit),
        .tx_ifg_val           (tx_ifg_val),
        .tx_status_vector     (),
        .tx_status_vld        (),
        .pause_req            (pause_req),
        .pause_val            (pause_val),
        .pause_source_addr    (pause_source_addr),
        .unicast_address      (unicast_address),
        .mac_cfg_vector       (mac_cfg_vector),
        .rgmii_txd            (o_rgmii_txd),
        .rgmii_tx_ctl         (o_rgmii_tx_ctl),
        .rgmii_txc            (o_rgmii_tx_clk),
        .rgmii_rxd            (i_rgmii_rxd),
        .rgmii_rx_ctl         (i_rgmii_rx_ctl),
        .rgmii_rxc            (rx_clk_pll_90_name),
        .inband_link_status   (inband_link_status),
        .inband_clock_speed   (inband_clock_speed),
        .inband_duplex_status (inband_duplex_status),
        .mdio_i               (1'b1),
        .mdio_o               (),
        .mdio_oen             (),
        .mdio_clk             ()
    );

    // ------------------------------------------------------------------------
    // Official asynchronous client FIFOs between TEMAC clocks and UDP clock.
    // ------------------------------------------------------------------------
    wire        temac_rx_ready;
    // rx_client_fifo LocalLink rd_src_rdy_n: active-low source-ready.
    // The official UDP stack RX-valid input is active-high, hence the
    // deliberate inversion at the stack boundary (same as vendor example).
    wire        temac_rx_valid;
    wire [7:0]  temac_rx_data;
    wire        temac_rx_sof;
    wire        temac_rx_eof;

    // The official stack TX-valid output and TX FIFO wr_src_rdy_n are both
    // active-low; keep this path direct, exactly as in the vendor example.
    wire        temac_tx_ready;
    wire        temac_tx_valid;
    wire [7:0]  temac_tx_data;
    wire        temac_tx_sof;
    wire        temac_tx_eof;

    wire        tx_fifo_overflow;
    wire [3:0]  tx_fifo_status;
    tx_client_fifo #(.DEVICE("EG4")) u_tx_client_fifo (
        .rd_clk          (tx_clk_int),
        .rd_sreset       (tx_domain_reset),
        .rd_enable       (tx_clk_en_int),
        .tx_data         (tx_data),
        .tx_data_valid   (tx_valid),
        .tx_ack          (tx_rdy),
        .tx_collision    (tx_collision),
        .tx_retransmit   (tx_retransmit),
        .overflow        (tx_fifo_overflow),
        .wr_clk          (udp_clk),
        .wr_sreset       (udp_domain_reset),
        .wr_data         (temac_tx_data),
        .wr_sof_n        (temac_tx_sof),
        .wr_eof_n        (temac_tx_eof),
        .wr_src_rdy_n    (temac_tx_valid),
        .wr_dst_rdy_n    (temac_tx_ready),
        .wr_fifo_status  (tx_fifo_status)
    );

    wire        rx_fifo_overflow;
    wire [3:0]  rx_fifo_status;
    rx_client_fifo #(.DEVICE("EG4")) u_rx_client_fifo (
        .wr_clk          (rx_clk_int),
        .wr_enable       (rx_clk_en_int),
        .wr_sreset       (rx_domain_reset),
        .rx_data         (rx_data),
        .rx_data_valid   (rx_valid),
        .rx_good_frame   (rx_correct_frame),
        .rx_bad_frame    (rx_error_frame),
        .overflow        (rx_fifo_overflow),
        .rd_clk          (udp_clk),
        .rd_sreset       (udp_domain_reset),
        .rd_data_out     (temac_rx_data),
        .rd_sof_n        (temac_rx_sof),
        .rd_eof_n        (temac_rx_eof),
        .rd_src_rdy_n    (temac_rx_valid),
        .rd_dst_rdy_n    (temac_rx_ready),
        .rx_fifo_status  (rx_fifo_status)
    );

    // ------------------------------------------------------------------------
    // Official UDP/IP/ARP protocol stack.
    // ------------------------------------------------------------------------
    reg [31:0] input_local_ip_address;
    reg        input_local_ip_address_valid;
    reg [15:0] input_local_udp_port_num;
    reg        input_local_udp_port_num_valid;

    always @(posedge udp_clk or posedge udp_domain_reset) begin
        if (udp_domain_reset) begin
            input_local_ip_address       <= LOCAL_IP;
            input_local_ip_address_valid <= 1'b0;
            input_local_udp_port_num       <= LOCAL_PORT;
            input_local_udp_port_num_valid <= 1'b0;
        end else begin
            input_local_ip_address       <= LOCAL_IP;
            input_local_ip_address_valid <= 1'b1;
            input_local_udp_port_num       <= LOCAL_PORT;
            input_local_udp_port_num_valid <= 1'b1;
        end
    end

    wire        udp_tx_ready;
    wire        app_tx_ack;
    wire        app_tx_request;
    wire        app_tx_data_valid;
    wire [7:0]  app_tx_data;
    wire [15:0] app_tx_data_length;
    wire        app_rx_data_valid;
    wire [7:0]  app_rx_data;
    wire [15:0] app_rx_data_length;
    wire [15:0] app_rx_port_num;
    wire        ip_rx_error;
    wire        arp_request_no_reply_error;

    wire [15:0] app_tx_dst_port = PC_PORT;
    wire [31:0] ip_tx_dst_address = PC_IP;

    udp_ip_protocol_stack #(
        .DEVICE             ("EG4"),
        .LOCAL_UDP_PORT_NUM(LOCAL_PORT),
        .LOCAL_IP_ADDRESS  (LOCAL_IP),
        .LOCAL_MAC_ADDRESS (LOCAL_MAC)
    ) u_udp_ip_protocol_stack (
        .udp_rx_clk                    (udp_clk),
        .udp_tx_clk                    (udp_clk),
        .reset                         (udp_domain_reset),
        .input_local_udp_port_num      (input_local_udp_port_num),
        .input_local_udp_port_num_valid(input_local_udp_port_num_valid),
        .udp2app_tx_ready              (udp_tx_ready),
        .udp2app_tx_ack                (app_tx_ack),
        .app_tx_request                (app_tx_request),
        .app_tx_data_valid             (app_tx_data_valid),
        .app_tx_data                   (app_tx_data),
        .app_tx_data_length            (app_tx_data_length),
        .app_rx_data_valid             (app_rx_data_valid),
        .app_rx_data                   (app_rx_data),
        .app_rx_data_length            (app_rx_data_length),
        .app_rx_port_num               (app_rx_port_num),
        .app_tx_dst_port               (app_tx_dst_port),
        .ip_tx_dst_address             (ip_tx_dst_address),
        .input_local_ip_address        (input_local_ip_address),
        .input_local_ip_address_valid  (input_local_ip_address_valid),
        .temac_rx_ready                (temac_rx_ready),
        .temac_rx_valid                (~temac_rx_valid),
        .temac_rx_data                 (temac_rx_data),
        .temac_rx_sof                  (temac_rx_sof),
        .temac_rx_eof                  (temac_rx_eof),
        .temac_tx_ready                (temac_tx_ready),
        .temac_tx_valid                (temac_tx_valid),
        .temac_tx_data                 (temac_tx_data),
        .temac_tx_sof                  (temac_tx_sof),
        .temac_tx_eof                  (temac_tx_eof),
        .ip_rx_error                   (ip_rx_error),
        .arp_request_no_reply_error    (arp_request_no_reply_error)
    );

    // ------------------------------------------------------------------------
    // QHMU application protocol adapter.
    // ------------------------------------------------------------------------
    wire       udp_app_rx_seen;
    wire       udp_app_tx_seen;
    wire [7:0] udp_app_rx_count;

    QHMU_NET_APP u_qhmu_net_app (
        .i_clk                    (udp_clk),
        .i_rst                    (udp_domain_reset),
        .i_app_rx_data_valid      (app_rx_data_valid),
        .i_app_rx_data            (app_rx_data),
        .i_app_rx_data_length     (app_rx_data_length),
        .i_app_rx_port_num        (app_rx_port_num),
        .i_udp_tx_ready           (udp_tx_ready),
        .i_app_tx_ack             (app_tx_ack),
        .o_app_tx_request         (app_tx_request),
        .o_app_tx_data_valid      (app_tx_data_valid),
        .o_app_tx_data            (app_tx_data),
        .o_app_tx_data_length     (app_tx_data_length),
        .i_status_brightness      (i_status_brightness),
        .i_status_contrast        (i_status_contrast),
        .i_status_transition      (i_status_transition),
        .i_status_image_index     (i_status_image_index),
        .i_status_file_count      (i_status_file_count),
        .i_status_auto            (i_status_auto),
        .i_status_audio_wait      (i_status_audio_wait),
        .o_cmd_toggle             (o_cmd_toggle),
        .o_cmd_code               (o_cmd_code),
        .o_cmd_value              (o_cmd_value),
        .o_udp_rx_seen            (udp_app_rx_seen),
        .o_udp_tx_seen            (udp_app_tx_seen),
        .o_udp_rx_count           (udp_app_rx_count)
    );

    // ------------------------------------------------------------------------
    // Bring-up diagnostics.
    //
    // LED activity is sticky: it latches after the first CRC-good frame.
    // The good/bad counters are separately reset by the RX-domain reset.
    // ------------------------------------------------------------------------
    reg [24:0] rx_heartbeat_div;
    reg        rx_good_seen_sticky;
    reg        rx_good_frame_d;
    reg        rx_bad_frame_d;
    wire       rx_good_frame_pulse = rx_correct_frame && !rx_good_frame_d;
    wire       rx_bad_frame_pulse  = rx_error_frame   && !rx_bad_frame_d;

    assign o_dbg_rx_clk_heartbeat = rx_heartbeat_div[24];
    // Sticky: once a CRC-good frame is received, LED3 stays on until reset.
    assign o_dbg_rx_activity      = rx_good_seen_sticky;
    assign o_dbg_phy_link         = inband_link_status;
    assign o_dbg_udp_seen         = udp_app_rx_seen;
    assign o_dbg_udp_packet_count = udp_app_rx_count;

    always @(posedge rx_clk_int or posedge rx_domain_reset) begin
        if (rx_domain_reset) begin
            rx_heartbeat_div            <= 25'd0;
            rx_good_seen_sticky         <= 1'b0;
            rx_good_frame_d             <= 1'b0;
            rx_bad_frame_d              <= 1'b0;
            o_dbg_rx_good_count         <= 8'd0;
            o_dbg_rx_bad_count          <= 8'd0;
            o_dbg_rx_valid_byte_count   <= 8'd0;
            o_dbg_rx_nonzero_byte_count <= 8'd0;
        end else begin
            rx_heartbeat_div <= rx_heartbeat_div + 1'b1;
            rx_good_frame_d  <= rx_correct_frame;
            rx_bad_frame_d   <= rx_error_frame;

            if (rx_good_frame_pulse) begin
                rx_good_seen_sticky <= 1'b1;
                if (o_dbg_rx_good_count != 8'hff)
                    o_dbg_rx_good_count <= o_dbg_rx_good_count + 1'b1;
            end

            if (rx_bad_frame_pulse && (o_dbg_rx_bad_count != 8'hff))
                o_dbg_rx_bad_count <= o_dbg_rx_bad_count + 1'b1;

            if (rx_valid) begin
                if (o_dbg_rx_valid_byte_count != 8'hff)
                    o_dbg_rx_valid_byte_count <= o_dbg_rx_valid_byte_count + 1'b1;
                if ((rx_data != 8'h00) && (o_dbg_rx_nonzero_byte_count != 8'hff))
                    o_dbg_rx_nonzero_byte_count <= o_dbg_rx_nonzero_byte_count + 1'b1;
            end
        end
    end

    // Stage 2: bytes accepted from the RX client FIFO by the protocol stack.
    // The official FIFO source-ready and destination-ready signals are active-low.
    always @(posedge udp_clk or posedge udp_domain_reset) begin
        if (udp_domain_reset) begin
            o_dbg_fifo_rx_byte_count      <= 8'd0;
            o_dbg_fifo_rx_nonzero_count   <= 8'd0;
            o_dbg_fifo_rx_sof_count       <= 8'd0;
            o_dbg_fifo_rx_eof_count       <= 8'd0;
            o_dbg_app_rx_byte_count       <= 8'd0;
            o_dbg_stack_tx_byte_count     <= 8'd0;
            o_dbg_stack_tx_nonzero_count <= 8'd0;
        end else begin
            if (!temac_rx_valid && !temac_rx_ready) begin
                if (o_dbg_fifo_rx_byte_count != 8'hff)
                    o_dbg_fifo_rx_byte_count <= o_dbg_fifo_rx_byte_count + 1'b1;
                if ((temac_rx_data != 8'h00) &&
                    (o_dbg_fifo_rx_nonzero_count != 8'hff))
                    o_dbg_fifo_rx_nonzero_count <= o_dbg_fifo_rx_nonzero_count + 1'b1;
                if (!temac_rx_sof && (o_dbg_fifo_rx_sof_count != 8'hff))
                    o_dbg_fifo_rx_sof_count <= o_dbg_fifo_rx_sof_count + 1'b1;
                if (!temac_rx_eof && (o_dbg_fifo_rx_eof_count != 8'hff))
                    o_dbg_fifo_rx_eof_count <= o_dbg_fifo_rx_eof_count + 1'b1;
            end

            if (app_rx_data_valid && (o_dbg_app_rx_byte_count != 8'hff))
                o_dbg_app_rx_byte_count <= o_dbg_app_rx_byte_count + 1'b1;

            // Stack-to-TX-FIFO interface: both active-low handshake signals low.
            if (!temac_tx_valid && !temac_tx_ready) begin
                if (o_dbg_stack_tx_byte_count != 8'hff)
                    o_dbg_stack_tx_byte_count <= o_dbg_stack_tx_byte_count + 1'b1;
                if ((temac_tx_data != 8'h00) &&
                    (o_dbg_stack_tx_nonzero_count != 8'hff))
                    o_dbg_stack_tx_nonzero_count <= o_dbg_stack_tx_nonzero_count + 1'b1;
            end
        end
    end

    // Stage 3: bytes actually presented by the TX FIFO to TEMAC.
    always @(posedge tx_clk_int or posedge tx_domain_reset) begin
        if (tx_domain_reset) begin
            o_dbg_mac_tx_byte_count    <= 8'd0;
            o_dbg_mac_tx_nonzero_count <= 8'd0;
        end else if (tx_clk_en_int && tx_valid) begin
            if (o_dbg_mac_tx_byte_count != 8'hff)
                o_dbg_mac_tx_byte_count <= o_dbg_mac_tx_byte_count + 1'b1;
            if ((tx_data != 8'h00) && (o_dbg_mac_tx_nonzero_count != 8'hff))
                o_dbg_mac_tx_nonzero_count <= o_dbg_mac_tx_nonzero_count + 1'b1;
        end
    end

    always @(posedge udp_clk or posedge udp_domain_reset) begin
        if (udp_domain_reset) begin
            o_dbg_arp_error             <= 1'b0;
            o_dbg_ip_error              <= 1'b0;
            o_dbg_rx_fifo_overflow_seen <= 1'b0;
            o_dbg_tx_fifo_overflow_seen <= 1'b0;
        end else begin
            if (arp_request_no_reply_error)
                o_dbg_arp_error <= 1'b1;
            if (ip_rx_error)
                o_dbg_ip_error <= 1'b1;
            if (rx_fifo_overflow)
                o_dbg_rx_fifo_overflow_seen <= 1'b1;
            if (tx_fifo_overflow)
                o_dbg_tx_fifo_overflow_seen <= 1'b1;
        end
    end

    // Keep the generated clocks and diagnostic-only signals visible to the
    // synthesis tool without creating extra top-level ports.
    wire _unused_debug = net_clk125_feedback ^ net_clk25 ^ net_clk1p25 ^ rx_clk_pll_0 ^
                         rx_clk_pll_250_unused ^ rx_pll_locked ^ udp_app_tx_seen ^
                         udp_app_rx_count[0] ^
                         tx_fifo_status[0] ^ rx_fifo_status[0] ^
                         inband_clock_speed[0] ^ inband_duplex_status;

