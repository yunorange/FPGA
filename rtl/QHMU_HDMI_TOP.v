    wire [7:0] brightness_pct_hex = {1'b0,brightness_pct_ctrl};
    wire [7:0] contrast_pct_hex   = {1'b0,contrast_pct_ctrl};
    wire [5:0] current_index_display = {1'b0,manager_current_index} + 6'd1;

    // Both counters are limited to 0..32. A small two-digit converter avoids
    // two unnecessary 16-bit double-dabble networks in the display path.
    function [7:0] bin6_to_bcd2;
        input [5:0] value;
        reg [3:0] tens;
        reg [5:0] ones;
        begin
            if (value >= 6'd30) begin tens=4'd3; ones=value-6'd30; end
            else if (value >= 6'd20) begin tens=4'd2; ones=value-6'd20; end
            else if (value >= 6'd10) begin tens=4'd1; ones=value-6'd10; end
            else begin tens=4'd0; ones=value; end
            bin6_to_bcd2 = {tens,ones[3:0]};
        end
    endfunction

    wire [7:0] file_count_bcd = bin6_to_bcd2(fat_file_count);
    wire [7:0] current_index_bcd = bin6_to_bcd2(current_index_display);

    // Eight digits: brightness(2 hex), contrast(2 hex), file count(2 decimal),
    // current image number(2 decimal). Transition/play mode are shown in OSD.
    wire [31:0] seg_digits = {
        brightness_pct_hex[7:4], brightness_pct_hex[3:0],
        contrast_pct_hex[7:4], contrast_pct_hex[3:0],
        file_count_bcd[7:4], file_count_bcd[3:0],
        current_index_bcd[7:4], current_index_bcd[3:0]
    };
    // SW3=1 selects network diagnostics. Page map:
    // SW2/SW1=00: MAC RX (good,bad,valid bytes,nonzero bytes)
    // SW2/SW1=01: RX FIFO (accepted bytes,nonzero,SOF,EOF)
    // SW2/SW1=10: UDP/IP (app RX bytes,UDP packets,error flags,reserved)
    // SW2/SW1=11: TX path (stack bytes/nonzero,MAC bytes/nonzero)
    wire [31:0] net_diag_page0 = {
        net_good_sync, net_bad_sync, net_valid_sync, net_nonzero_sync
    };
    wire [31:0] net_diag_page1 = {
        net_fifo_bytes_sync, net_fifo_nz_sync, net_fifo_sof_sync, net_fifo_eof_sync
    };
    wire [31:0] net_diag_page2 = {
        net_app_bytes_sync, net_udp_sync, 4'h0, net_flags_sync, 8'h00
    };
    wire [31:0] net_diag_page3 = {
        net_stack_tx_bytes_sync, net_stack_tx_nz_sync,
        net_mac_tx_bytes_sync, net_mac_tx_nz_sync
    };
    reg [31:0] net_diag_digits;
    always @* begin
        case ({net_diag_page_sync, net_diag_subpage_sync})
            2'b00: net_diag_digits = net_diag_page0;
            2'b01: net_diag_digits = net_diag_page1;
            2'b10: net_diag_digits = net_diag_page2;
            default: net_diag_digits = net_diag_page3;
        endcase
    end
    wire [31:0] seg_digits_display = net_diag_switch_sync ? net_diag_digits : seg_digits;

    QHMU_SEG7_DRIVER u_seg7(
        .i_clk(clk_ctrl), .i_rst(rst_ctrl), .i_digits(seg_digits_display),
        .o_seg(O_SEG), .o_sel(O_DIG_SEL));

    // Official Anlogic TEMAC + UDP/IP/ARP network path.  The original HDMI,
    // SDRAM, SD/FAT32, image and WAV playback logic remains unchanged.
    QHMU_RGMII_TEMAC_UDP u_net_control(
        .i_clk_50m(I_CLK_50M), .i_reset(rst_ctrl),
        .i_rgmii_rx_clk(I_PHY_RGMII_RX_CLK),
        .i_rgmii_rx_ctl(I_PHY_RGMII_RX_CTL),
        .i_rgmii_rxd(I_PHY_RGMII_RXD),
        .o_rgmii_tx_clk(O_PHY_RGMII_TX_CLK),
        .o_rgmii_tx_ctl(O_PHY_RGMII_TX_CTL),
        .o_rgmii_txd(O_PHY_RGMII_TXD),
        .i_status_brightness(brightness_pct_ctrl),
        .i_status_contrast(contrast_pct_ctrl),
        .i_status_transition(ui_transition_mode),
        .i_status_image_index({1'b0,manager_current_index}),
        .i_status_file_count(fat_file_count),
        .i_status_auto(manager_auto_mode),
        .i_status_audio_wait(audio_wait_mode_ctrl),
        .o_cmd_toggle(net_cmd_toggle), .o_cmd_code(net_cmd_code),
        .o_cmd_value(net_cmd_value),
        .o_dbg_rx_clk_heartbeat(net_dbg_rx_clk_heartbeat),
        .o_dbg_rx_activity(net_dbg_rx_activity),
        .o_dbg_phy_link(net_dbg_phy_link),
        .o_dbg_udp_seen(net_dbg_udp_seen),
        .o_dbg_arp_error(net_dbg_arp_error),
        .o_dbg_ip_error(net_dbg_ip_error),
        .o_dbg_rx_good_count(net_dbg_rx_good_count),
        .o_dbg_rx_bad_count(net_dbg_rx_bad_count),
        .o_dbg_rx_valid_byte_count(net_dbg_rx_valid_byte_count),
        .o_dbg_rx_nonzero_byte_count(net_dbg_rx_nonzero_byte_count),
        .o_dbg_udp_packet_count(net_dbg_udp_packet_count),
        .o_dbg_rx_fifo_overflow_seen(net_dbg_rx_fifo_overflow),
        .o_dbg_tx_fifo_overflow_seen(net_dbg_tx_fifo_overflow),
        .o_dbg_fifo_rx_byte_count(net_dbg_fifo_rx_byte_count),
        .o_dbg_fifo_rx_nonzero_count(net_dbg_fifo_rx_nonzero_count),
        .o_dbg_fifo_rx_sof_count(net_dbg_fifo_rx_sof_count),
        .o_dbg_fifo_rx_eof_count(net_dbg_fifo_rx_eof_count),
        .o_dbg_app_rx_byte_count(net_dbg_app_rx_byte_count),
        .o_dbg_stack_tx_byte_count(net_dbg_stack_tx_byte_count),
        .o_dbg_stack_tx_nonzero_count(net_dbg_stack_tx_nonzero_count),
        .o_dbg_mac_tx_byte_count(net_dbg_mac_tx_byte_count),
        .o_dbg_mac_tx_nonzero_count(net_dbg_mac_tx_nonzero_count)
    );

    reg status_error_d;
    wire status_error = fat_error | manager_error | video_underrun | wav_error | subtitle_error | osd_font_error;
    wire error_rise = status_error & ~status_error_d;
    always @(posedge clk_ctrl or posedge rst_ctrl) begin
        if (rst_ctrl) status_error_d <= 1'b0;
        else status_error_d <= status_error;
    end
    QHMU_BUZZER u_buzzer(
        .i_clk(clk_ctrl), .i_rst(rst_ctrl),
        .i_trigger(ui_next | ui_prev | ui_auto_toggle | transition_done_ctrl | error_rise),
        .o_buzzer(O_BUZZER));

        wire _unused_status = fat_subtitle_busy ^ fat_subtitle_present ^ subtitle_format_ok ^
                              fat_font_present ^ osd_font_loaded ^ fat_music_count ^ fat_audio_count ^
                              wav_format_ok ^ wav_error ^ audio_underflow_pulse;

    // hdmi_ready is intentionally not used to stall an active line.  APUG092's
    // external video source is timing driven; the core performs phase matching
    // and only deasserts READY between complete lines.
endmodule
