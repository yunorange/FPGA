    // ------------------------------------------------------------------------
    // Human-readable brightness / contrast display mapping
    //
    // The image-processing path keeps using the original raw controls:
    //   brightness : -96 ... 0 ... +96
    //   contrast   :  48 ...128... 240
    //
    // OSD / seven-segment display uses an intuitive 0...100 scale:
    //   brightness : -96 -> 0,   0 -> 50,  +96 -> 100
    //   contrast   :  48 -> 0, 128 -> 50,  240 -> 100
    //
    // The controls change in steps of 8, so lookup tables are used instead
    // of hardware dividers.  This is intentionally conservative for TD.    // ------------------------------------------------------------------------
    function [6:0] brightness_to_pct;
        input signed [7:0] value;
        begin
            case (value)
                -8'sd96: brightness_to_pct = 7'd0;
                -8'sd88: brightness_to_pct = 7'd4;
                -8'sd80: brightness_to_pct = 7'd8;
                -8'sd72: brightness_to_pct = 7'd13;
                -8'sd64: brightness_to_pct = 7'd17;
                -8'sd56: brightness_to_pct = 7'd21;
                -8'sd48: brightness_to_pct = 7'd25;
                -8'sd40: brightness_to_pct = 7'd29;
                -8'sd32: brightness_to_pct = 7'd33;
                -8'sd24: brightness_to_pct = 7'd38;
                -8'sd16: brightness_to_pct = 7'd42;
                -8'sd8 : brightness_to_pct = 7'd46;
                 8'sd0 : brightness_to_pct = 7'd50;
                 8'sd8 : brightness_to_pct = 7'd54;
                 8'sd16: brightness_to_pct = 7'd58;
                 8'sd24: brightness_to_pct = 7'd63;
                 8'sd32: brightness_to_pct = 7'd67;
                 8'sd40: brightness_to_pct = 7'd71;
                 8'sd48: brightness_to_pct = 7'd75;
                 8'sd56: brightness_to_pct = 7'd79;
                 8'sd64: brightness_to_pct = 7'd83;
                 8'sd72: brightness_to_pct = 7'd88;
                 8'sd80: brightness_to_pct = 7'd92;
                 8'sd88: brightness_to_pct = 7'd96;
                 8'sd96: brightness_to_pct = 7'd100;
                default: begin
                    if (value <= -8'sd96)
                        brightness_to_pct = 7'd0;
                    else if (value >= 8'sd96)
                        brightness_to_pct = 7'd100;
                    else
                        brightness_to_pct = 7'd50;
                end
            endcase
        end
    endfunction

    function [6:0] contrast_to_pct;
        input [7:0] value;
        begin
            case (value)
                 8'd48 : contrast_to_pct = 7'd0;
                 8'd56 : contrast_to_pct = 7'd5;
                 8'd64 : contrast_to_pct = 7'd10;
                 8'd72 : contrast_to_pct = 7'd15;
                 8'd80 : contrast_to_pct = 7'd20;
                 8'd88 : contrast_to_pct = 7'd25;
                 8'd96 : contrast_to_pct = 7'd30;
                 8'd104: contrast_to_pct = 7'd35;
                 8'd112: contrast_to_pct = 7'd40;
                 8'd120: contrast_to_pct = 7'd45;
                 8'd128: contrast_to_pct = 7'd50;
                 8'd136: contrast_to_pct = 7'd54;
                 8'd144: contrast_to_pct = 7'd57;
                 8'd152: contrast_to_pct = 7'd61;
                 8'd160: contrast_to_pct = 7'd64;
                 8'd168: contrast_to_pct = 7'd68;
                 8'd176: contrast_to_pct = 7'd71;
                 8'd184: contrast_to_pct = 7'd75;
                 8'd192: contrast_to_pct = 7'd79;
                 8'd200: contrast_to_pct = 7'd82;
                 8'd208: contrast_to_pct = 7'd86;
                 8'd216: contrast_to_pct = 7'd89;
                 8'd224: contrast_to_pct = 7'd93;
                 8'd232: contrast_to_pct = 7'd96;
                 8'd240: contrast_to_pct = 7'd100;
                default: begin
                    if (value <= 8'd48)
                        contrast_to_pct = 7'd0;
                    else if (value >= 8'd240)
                        contrast_to_pct = 7'd100;
                    else
                        contrast_to_pct = 7'd50;
                end
            endcase
        end
    endfunction

