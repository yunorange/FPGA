// ============================================================================
// QHMU_HDMI_TOP
// Project: QHMU_HDMI_PRO
// Target : Anlogic EG4S20BG256 / HX4S20C
//
// Integrated functions:
//   * FAT32 SD/TF scan of PICxxxx.BMP, MUSxxxx.WAV and AUDxxxx.WAV
//   * Native variable-resolution 24-bit BMP parsing directly on FPGA
//   * 8-MiB internal SDRAM double frame buffer 
//   * Manual MUS circular playlist; auto timed AUD / auto variable MUS
//   * Aspect-ratio-preserving nearest-neighbor scaling to 1920x1080p30 HDMI
//   * Ten transitions: cut, fade, horizontal wipe, smooth, push, split,
//     cut-in, reveal, cover, and a low-cost clockwise quadrant sweep
//   * Brightness / contrast adjustment
//   * Always-on Chinese OSD and scrolling subtitle; optional audio visualizer
//   * FAT32 WAV playback: 48-kHz stereo PCM16 from SD/TF card
//   * HDMI ACR CTS/N generation from the real 48-kHz PCM stream
//   * Integrated RGMII ARP/UDP control and status on this same top-level
//   * APUG092 HDMI1.4b protocol core + EG4 TMDS PHY
// ============================================================================
